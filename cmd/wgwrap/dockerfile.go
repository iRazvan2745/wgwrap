package main

import (
	"encoding/json"
	"fmt"
	"slices"
	"strings"
)

const (
	labelSource  = "io.wgwrap.source"
	labelVersion = "io.wgwrap.version"
	initPath     = "/wgwrap-init"
)

// imageConfig is the subset of the OCI image config we care about.
type imageConfig struct {
	Entrypoint []string
	Cmd        []string
	User       string
	Env        []string
	Labels     map[string]string
}

// original undoes a previous wrap so we re-wrap the real entrypoint instead of stacking inits.
// It returns the config the app image had before wgwrap, and its original source name.
func (c imageConfig) original(name string) (imageConfig, string) {
	src, wrapped := c.Labels[labelSource]
	if !wrapped {
		return c, name
	}
	o := c
	if len(o.Entrypoint) >= 2 && o.Entrypoint[0] == initPath && o.Entrypoint[1] == "--" {
		o.Entrypoint = o.Entrypoint[2:]
	}
	o.User = ""
	for _, kv := range o.Env {
		if v, ok := strings.CutPrefix(kv, "WGWRAP_USER="); ok {
			o.User = v
		}
	}
	return o, src
}

type buildSpec struct {
	Source    string // image to build FROM
	Origin    string // original, never-wrapped image, for the label
	InitImage string
	Version   string
	Orig      imageConfig
	BakeConf  bool // COPY wg0.conf into the image
	Optional  bool
}

func jsonArray(a []string) string {
	if a == nil {
		a = []string{}
	}
	var b strings.Builder
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	_ = enc.Encode(a)
	return strings.TrimSpace(b.String())
}

func jsonString(s string) string {
	b, _ := json.Marshal(s)
	return string(b)
}

func generateDockerfile(s buildSpec) string {
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f+"\n", a...) }
	w("# generated by wgwrap %s", s.Version)
	w("FROM %s AS wgwrap", s.InitImage)
	w("FROM %s", s.Source)
	w("COPY --from=wgwrap %s %s", initPath, initPath)
	if s.BakeConf {
		w("COPY --chmod=0600 wg0.conf /etc/wireguard/wg0.conf")
	}
	w("USER root")
	w("ENV WGWRAP_USER=%s", jsonString(s.Orig.User))
	if s.Optional {
		w("ENV WG_OPTIONAL=1")
	}
	w("ENTRYPOINT %s", jsonArray(slices.Concat([]string{initPath, "--"}, s.Orig.Entrypoint)))
	// Setting ENTRYPOINT clears the inherited CMD, so it must be re-set.
	if len(s.Orig.Cmd) > 0 {
		w("CMD %s", jsonArray(s.Orig.Cmd))
	}
	w("LABEL %s=%s %s=%s", labelSource, jsonString(s.Origin), labelVersion, jsonString(s.Version))
	return b.String()
}
